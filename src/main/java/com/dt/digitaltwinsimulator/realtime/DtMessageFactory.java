package com.dt.digitaltwinsimulator.realtime;

import com.dt.digitaltwinsimulator.logic.RandomValueGenerator;
import org.springframework.stereotype.Component;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

import java.time.Instant;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.*;
import java.util.concurrent.ThreadLocalRandom;
import java.util.regex.Pattern;

@Component
public class DtMessageFactory {
    private static final DateTimeFormatter TIMESTAMP = DateTimeFormatter.ofPattern("yyyyMMddHHmmssSSS");
    private static final Pattern TOKEN = Pattern.compile("\\{\\{([^{}]*)}}", Pattern.DOTALL);
    private static final Set<String> STANDARD = Set.of("dx-schema-version", "dx-message-id", "dx-sent-at");
    private static final Set<String> RESERVED = Set.of("NULL", "TRUE", "FALSE", "NOT", "AND", "OR", "BETWEEN", "LIKE", "IN", "IS", "ESCAPE");
    private final JsonMapper mapper;
    private final RealtimeProperties properties;

    public DtMessageFactory(JsonMapper mapper, RealtimeProperties properties) {
        this.mapper = mapper;
        this.properties = properties;
    }

    public record Spec(String messageId, RealtimeRequest.Envelope envelope, Map<String, String> headers, boolean standardHeaders) {}
    public record Message(JsonNode object, String body, Map<String, String> headers) {}

    /** Per publication/stream token state. Never shared between streams or with preview. */
    public static final class TokenState {
        private final Map<String, Double> walks = new HashMap<>();
        TokenState copy() {
            var copy = new TokenState();
            copy.walks.putAll(walks);
            return copy;
        }
    }

    public Spec specification(RealtimeRequest request) {
        if (request.getEnvelope() == null) throw new IllegalArgumentException("envelope is required.");
        if (request.getEnvelope() == RealtimeRequest.Envelope.DTCORE &&
                (request.getMessageId() == null || request.getMessageId().isBlank())) {
            throw new IllegalArgumentException("messageId is required for DTCORE.");
        }
        Map<String, String> headers = new LinkedHashMap<>();
        Map<String, String> input = request.getHeaders() == null ? Map.of() : request.getHeaders();
        input.forEach((name, value) -> {
            if (!validHeader(name) || value == null) throw new IllegalArgumentException("Invalid JMS header name or null value.");
            if (request.isStandardHeaders() && (STANDARD.contains(name) || STANDARD.contains(name.replace('_', '-')))) {
                throw new IllegalArgumentException("Standard headers are generated by the server and cannot be overridden.");
            }
            String property = STANDARD.contains(name) ? name.replace('-', '_') : name;
            if (headers.putIfAbsent(property, value) != null) throw new IllegalArgumentException("Duplicate normalized JMS header.");
        });
        return new Spec(request.getMessageId(), request.getEnvelope(), Map.copyOf(headers), request.isStandardHeaders());
    }

    private boolean validHeader(String name) {
        // Channel names are accepted at the API and mapped to JMS identifiers before publication.
        if (name == null || name.isEmpty()) return false;
        if (STANDARD.contains(name)) return true;
        if (name.startsWith("JMS") || name.startsWith("JMSX") || RESERVED.contains(name.toUpperCase(Locale.ROOT))) return false;
        if (!Character.isJavaIdentifierStart(name.charAt(0))) return false;
        for (int i = 1; i < name.length(); i++) if (!Character.isJavaIdentifierPart(name.charAt(i))) return false;
        return true;
    }

    public void validatePayload(Spec spec, JsonNode payload) {
        validateShape(spec, payload);
        visit(payload, "", 1, new TokenState(), true);
    }

    void validateShape(Spec spec, JsonNode payload) {
        if (payload == null) throw new IllegalArgumentException("payload is required.");
        if (spec.envelope() == RealtimeRequest.Envelope.DTCORE && !payload.isObject()) {
            throw new IllegalArgumentException("DTCORE payload must be a JSON object.");
        }
    }

    public Message create(Spec spec, JsonNode payload, long sequence, TokenState state) {
        JsonNode rendered = visit(payload, "", sequence, state, false);
        return createLiteral(spec, rendered);
    }

    /** Independent candidate state, committed by scenario playback only after a successful send. */
    public TokenState copyTokenState(TokenState state) { return state.copy(); }

    /** File values are literals: CSV cells must never be interpreted as generation tokens. */
    public void validateLiteralPayload(Spec spec, JsonNode payload) { validateShape(spec, payload); }

    public Message createLiteralMessage(Spec spec, JsonNode payload) { return createLiteral(spec, payload); }

    /** Isolate stateful fields on different destinations while keeping one run-wide sequence. */
    public Message createForScope(Spec spec, JsonNode payload, long sequence, TokenState state, String scope) {
        return createLiteral(spec, visit(payload, scope, sequence, state, false));
    }

    Message createLiteral(Spec spec, JsonNode rendered) {
        var body = rendered;
        if (spec.envelope() == RealtimeRequest.Envelope.DTCORE) {
            String timestamp = LocalDateTime.now().format(TIMESTAMP);
            var envelope = mapper.createObjectNode();
            envelope.put("CREATE_TIMESTAMP", timestamp);
            envelope.put("MESSAGE_ID", spec.messageId());
            envelope.putObject("DATA_MAP").set(timestamp, rendered);
            body = envelope;
        }
        var headers = new LinkedHashMap<>(spec.headers());
        if (spec.standardHeaders()) {
            headers.put("dx_schema_version", properties.getSchemaVersion());
            headers.put("dx_message_id", UUID.randomUUID().toString());
            headers.put("dx_sent_at", Instant.now().toString());
        }
        // RAW strings are sent as their actual text; arbitrary JSON retains its JSON encoding.
        String text = spec.envelope() == RealtimeRequest.Envelope.RAW && body.isString()
                ? body.asString() : mapper.writeValueAsString(body);
        return new Message(body, text, Map.copyOf(headers));
    }

    private JsonNode visit(JsonNode node, String path, long seq, TokenState state, boolean validate) {
        if (node.isObject()) {
            var result = mapper.createObjectNode();
            node.properties().forEach(e -> result.set(e.getKey(), visit(e.getValue(), path + "/" +
                    e.getKey().replace("~", "~0").replace("/", "~1"), seq, state, validate)));
            return result;
        }
        if (node.isArray()) {
            var result = mapper.createArrayNode();
            for (int i = 0; i < node.size(); i++) result.add(visit(node.get(i), path + "/" + i, seq, state, validate));
            return result;
        }
        if (!node.isString()) return node.deepCopy();
        String input = node.asString();
        var matcher = TOKEN.matcher(input);
        if (matcher.matches()) return mapper.valueToTree(token(matcher.group(1), path, seq, state, validate));
        matcher.reset();
        StringBuilder result = new StringBuilder();
        int end = 0;
        while (matcher.find()) {
            String literal = input.substring(end, matcher.start());
            rejectBraces(literal);
            result.append(literal).append(token(matcher.group(1), path + "@" + matcher.start(), seq, state, validate));
            end = matcher.end();
        }
        String tail = input.substring(end);
        rejectBraces(tail);
        return mapper.valueToTree(result.append(tail).toString());
    }

    private void rejectBraces(String text) {
        if (text.contains("{{") || text.contains("}}")) throw new IllegalArgumentException("Malformed value token.");
    }

    private Object token(String expression, String path, long seq, TokenState state, boolean validate) {
        String token = expression.trim();
        try {
            if (token.equals("seq")) return seq;
            if (token.equals("uuid")) return validate ? "uuid" : UUID.randomUUID().toString();
            if (token.equals("now") || token.startsWith("now:")) {
                var format = token.equals("now") ? TIMESTAMP : DateTimeFormatter.ofPattern(token.substring(4));
                return LocalDateTime.now().format(format);
            }
            if (token.startsWith("random:")) {
                String[] parts = token.split(":", 3);
                if (parts.length != 3) throw new IllegalArgumentException();
                String type = parts[1].toLowerCase(Locale.ROOT);
                if (!Set.of("string", "integer", "int", "long", "double", "float", "number", "boolean", "bool", "date", "datetime", "timestamp").contains(type)) throw new IllegalArgumentException();
                String value = RandomValueGenerator.generate(type, parts[2]);
                return switch (type) {
                    case "integer", "int", "long" -> Long.parseLong(value);
                    case "double", "float", "number" -> finite(Double.parseDouble(value));
                    case "boolean", "bool" -> Boolean.parseBoolean(value);
                    default -> value;
                };
            }
            if (token.startsWith("walk:")) {
                String[] parts = token.split(":", -1);
                if (parts.length != 4) throw new IllegalArgumentException();
                String[] range = parts[2].split("\\.\\.", -1);
                if (range.length != 2) throw new IllegalArgumentException();
                double start = finite(Double.parseDouble(parts[1]));
                double min = finite(Double.parseDouble(range[0])), max = finite(Double.parseDouble(range[1]));
                double change = finite(Double.parseDouble(parts[3]));
                if (min > max || start < min || start > max || change < 0 || !Double.isFinite(max - min) || !Double.isFinite(change * 2)) throw new IllegalArgumentException();
                String key = path + ":" + token;
                double previous = state.walks.getOrDefault(key, start);
                double value = validate || !state.walks.containsKey(key) || change == 0 ? previous
                        : Math.clamp(previous + ThreadLocalRandom.current().nextDouble(-change, change), min, max);
                if (!validate) state.walks.put(key, value);
                return value;
            }
            if (token.startsWith("cycle:") || token.startsWith("pick:")) {
                String[] values = token.substring(token.indexOf(':') + 1).split("\\|", -1);
                if (Arrays.stream(values).anyMatch(String::isEmpty)) throw new IllegalArgumentException();
                return values[token.startsWith("cycle:") ? (int) ((seq - 1) % values.length) : ThreadLocalRandom.current().nextInt(values.length)];
            }
        } catch (RuntimeException e) {
            throw new IllegalArgumentException("Invalid value token (" + token.split(":", 2)[0] + ").");
        }
        throw new IllegalArgumentException("Unknown value token.");
    }

    private double finite(double value) {
        if (!Double.isFinite(value)) throw new IllegalArgumentException();
        return value;
    }
}
